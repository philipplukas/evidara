"""Experiment 9 -- break one assumption at a time and watch how it fails.

Showing that the correct model works on data generated by the correct model is the least
informative thing this laboratory can do. Six assumptions are violated one at a time,
each with a matched control that runs the identical estimator on data that satisfies it:

  1 wrong dynamics       cubic stiffness generated, linear fitted
  2 wrong kernel         two temporal modes generated, one fitted
  3 wrong noise          correlated Sigma generated, isotropic assumed
  4 wrong speaker geom.  groupoid charts generated, a single group chart fitted
  5 wrong acoustic map   strongly nonlinear Phi generated, a linear map fitted
  6 wrong dimensionality d_art = 5 generated, d = 2 assumed

The output of each row is not just "worse" but *how*: which quantity moves, whether the
residual still looks like noise, and whether anything in the fit would have warned you.
"""

from __future__ import annotations

from dataclasses import replace

import matplotlib.pyplot as plt
import numpy as np
from _common import MUTED, PALETTE, caption, parse_args, save

from analysis.identifiability import spectral_invariants
from analysis.kernels import fit_modal_model
from analysis.metrics import relative_error, rmse
from analysis.recording import ExperimentRun
from analysis.svd import all_contrasts, stack_contrasts
from analysis.system_id import fit_trajectory_second_order, invert_nonlinear
from config import SequenceConfig, WorldConfig, dimension_world, noise_world, speaker_world
from generator import generate

NOISE = 0.1


def base_world(n_seq: int) -> WorldConfig:
    return noise_world("correlated", NOISE, replace(WorldConfig(), sequence=SequenceConfig(n_sequences=n_seq)))


def invert_with(ds, phi):
    """Invert the per-transition mean acoustics with a *supplied* map (not necessarily the true one)."""
    U, U0 = [], []
    for q, r in ds.transitions:
        S = ds.observed[ds.mask(q, r)].mean(axis=0)
        u0 = np.zeros(phi.d_art)
        U.append(invert_nonlinear(S, phi.Phi, u0, phi.Dphi))
        U0.append(U[-1][0])
    return np.stack(U), np.stack(U0)


def pole_error(fit, world) -> float:
    truth = spectral_invariants(
        -np.linalg.inv(world.dynamics.M) @ world.dynamics.K,  # GT: scoring
        -np.linalg.inv(world.dynamics.M) @ world.dynamics.C,  # GT
    )
    return relative_error(np.real(fit.poles()), np.real(truth))


def residual_structure(resid: np.ndarray) -> float:
    """Lag-1 autocorrelation of the residual, averaged over dimensions.

    White residual -> ~0. A structured residual is the fit telling you the model is wrong,
    and it is the only warning most of these violations give.
    """
    r = resid.reshape(-1, resid.shape[-1])
    out = []
    for j in range(r.shape[1]):
        x = r[:-1, j] - r[:, j].mean()
        y = r[1:, j] - r[:, j].mean()
        denom = np.sqrt((x**2).sum() * (y**2).sum())
        out.append(float((x * y).sum() / denom) if denom > 0 else 0.0)
    return float(np.mean(out))


def main() -> None:
    args = parse_args(__doc__)
    n_seq = 500 if args.quick else 3000
    run = ExperimentRun(name="09_assumption_stress_test", title="Experiment 9 -- assumption stress test")
    run.scalar("n_sequences", n_seq)
    run.scalar("noise_scale", NOISE)
    rows = {}
    base = base_world(n_seq)

    # ---- 1. wrong dynamics ---------------------------------------------------------------
    ok = generate(base, seed=args.seed)
    nl_world = replace(base, dynamics=replace(base.dynamics, cubic_gain=4.0))  # GT: builds the violation
    nl = generate(nl_world, seed=args.seed)
    res = {}
    for label, ds in (("control (linear)", ok), ("violated (cubic stiffness)", nl)):
        U, U0 = invert_with(ds, ds.phi)  # ORACLE: correct acoustic map, so only dynamics are wrong
        fit = fit_trajectory_second_order(U, ds.config.grid.dt, U0)
        pred = np.stack([fit.targets[i] for i in range(len(ds.transitions))])
        res[label] = dict(
            pole_error=pole_error(fit, ds.config),
            residual_rmse=fit.residual_rmse,
            residual_lag1_autocorr=residual_structure(U - _simulate_like(fit, U, U0, ds.config.grid.dt)),
        )
        _ = pred
    rows["1 wrong dynamics"] = res

    # ---- 2. wrong kernel (one mode fitted to two) -----------------------------------------
    X = stack_contrasts(all_contrasts(ok))
    m1 = fit_modal_model(ok.t, X, 1, seed=args.seed)
    m2 = fit_modal_model(ok.t, X, 2, seed=args.seed)
    rows["2 wrong kernel"] = {
        "control (2 modes fitted)": dict(residual_rmse=m2.residual_rmse,
                                         omega=[float(x) for x in m2.omega]),
        "violated (1 mode fitted)": dict(residual_rmse=m1.residual_rmse,
                                         omega=[float(x) for x in m1.omega],
                                         residual_lag1_autocorr=residual_structure(X - m1.predict(ok.t))),
    }

    # ---- 3. wrong noise model --------------------------------------------------------------
    # deliberately run at high noise: at NOISE = 0.1 both likelihoods classify perfectly and
    # the comparison would report "no difference" for the uninteresting reason
    strong = generate(noise_world("strong", 2.0, base), seed=args.seed)
    sigma_true = strong.noise_model.sigma  # GT: what the data actually has
    sigma_iso = np.eye(sigma_true.shape[0]) * np.trace(sigma_true) / sigma_true.shape[0]
    templates = np.stack([strong.clean[strong.mask(q, r)][0] for q, r in strong.transitions])  # GT: exact templates
    y_true = strong.transition  # GT: the label
    acc = {}
    for label, sig in (("control (correct Sigma)", sigma_true), ("violated (isotropic Sigma)", sigma_iso)):
        prec = np.linalg.inv(sig)
        r = strong.observed[:, None, :, :] - templates[None, :, :, :]
        ll = -0.5 * np.einsum("nctd,de,ncte->nc", r, prec, r, optimize=True)
        acc[label] = dict(accuracy=float(np.mean(np.argmax(ll, axis=1) == y_true)))
    rows["3 wrong noise"] = acc

    # ---- 4. wrong speaker geometry -----------------------------------------------------------
    rows["4 wrong speaker geometry"] = _speaker_row(base, args.seed)

    # ---- 5. wrong acoustic map ---------------------------------------------------------------
    sn_world = replace(base, acoustic=replace(base.acoustic, kind="strong_nonlinear"))
    sn = generate(sn_world, seed=args.seed)
    lin_phi = _best_linear_map(sn)
    res = {}
    for label, phi in (("control (true Phi)", sn.phi), ("violated (linear Phi)", lin_phi)):  # ORACLE: control
        U, U0 = invert_with(sn, phi)
        fit = fit_trajectory_second_order(U, sn.config.grid.dt, U0)
        res[label] = dict(pole_error=pole_error(fit, sn.config), residual_rmse=fit.residual_rmse)
    rows["5 wrong acoustic map"] = res

    # ---- 6. wrong dimensionality --------------------------------------------------------------
    d5 = generate(noise_world("correlated", NOISE, dimension_world(5, 10, base)), seed=args.seed)
    res = {}
    U5, U05 = invert_with(d5, d5.phi)  # ORACLE: correct map, correct dimension
    fit5 = fit_trajectory_second_order(U5, d5.config.grid.dt, U05)
    U2 = U5[:, :, :2]  # a 2-dimensional model can only carry a 2-dimensional latent
    fit2 = fit_trajectory_second_order(U2, d5.config.grid.dt, U05[:, :2])
    truth5 = np.real(spectral_invariants(
        -np.linalg.inv(d5.config.dynamics.M) @ d5.config.dynamics.K,  # GT
        -np.linalg.inv(d5.config.dynamics.M) @ d5.config.dynamics.C,  # GT
    ))

    # Scored on a metric the two models can BOTH be held to: how well each reconstructs the
    # first two latent dimensions. Comparing pole sets directly would be meaningless -- the
    # d = 2 fit has 4 poles against the truth's 10, and any subset-matching rule flatters it
    # for describing less. Both pole sets are still reported, with that caveat attached.
    recon5 = _simulate_like(fit5, U5, U05, d5.config.grid.dt)[:, :, :2]
    recon2 = _simulate_like(fit2, U2, U05[:, :2], d5.config.grid.dt)
    res["control (d = 5 assumed)"] = dict(
        retained_dim_reconstruction_rmse=rmse(U2, recon5),
        pole_error_all_10=pole_error(fit5, d5.config),
        n_poles=int(fit5.poles().size),
    )
    got2 = np.real(fit2.poles())
    res["violated (d = 2 assumed)"] = dict(
        retained_dim_reconstruction_rmse=rmse(U2, recon2),
        pole_error_best_subset=float(np.min([
            relative_error(np.sort(got2), np.sort(truth5)[i : i + got2.size])
            for i in range(len(truth5) - got2.size + 1)
        ])),
        n_poles=int(got2.size),
        caveat="the best-subset pole score is generous by construction: it rewards the model for "
               "describing 4 of the 10 true poles and ignores the 6 it cannot represent",
    )
    rows["6 wrong dimensionality"] = res

    for k, v in rows.items():
        run.table(k, v)

    # ---- findings ------------------------------------------------------------------------------
    def pair(key, metric):
        vals = list(rows[key].values())
        return vals[0].get(metric), vals[1].get(metric)

    for key, metric, label, mode in (
        ("1 wrong dynamics", "pole_error", "relative pole error",
         "the linear fit still converges and still reports a plausible second-order system; the "
         "warning is in the residual, which stops looking like noise (see the right-hand panel)"),
        ("2 wrong kernel", "residual_rmse", "residual rmse",
         "a one-mode fit absorbs the missing mode into a compromise pole, so the reported time "
         "constant is wrong while the fit still looks good"),
        ("3 wrong noise", "accuracy", "classification accuracy",
         "an isotropic likelihood mis-weights the correlated directions and loses accuracy with no "
         "diagnostic at all -- the model never sees its own mis-specification"),
        ("4 wrong speaker geometry", "held_out_rmse", "held-out rmse",
         "a global chart cannot absorb phone-local deviations that average to zero across phones, "
         "so the error is systematic rather than noisy"),
        ("5 wrong acoustic map", "pole_error", "relative pole error",
         "a linear inverse of a saturating map warps the latent nonlinearly in time, which the "
         "dynamics fit then reads as the wrong damping"),
        ("6 wrong dimensionality", "pole_error", "relative pole error",
         "the missing latent dimensions do not vanish -- they appear as unexplained structure in "
         "the retained ones, and the fit reports plausible poles for a system that is not there"),
    ):
        ctrl, viol = pair(key, metric)
        if ctrl is None or viol is None:
            continue
        run.record(
            question=f"What happens under: {key}?",
            ground_truth={"control value of " + label: round(float(ctrl), 5)},
            estimate={"violated value of " + label: round(float(viol), 5)},
            error=float(abs(viol - ctrl) / max(abs(ctrl), 1e-12)),
            error_label=f"relative change in {label}",
            status="MIS-SPECIFIED",
            control=list(rows[key])[0],
            notes=f"{label} goes {float(ctrl):.4g} -> {float(viol):.4g}. {mode}",
        )

    # ---- figure ---------------------------------------------------------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))

    ax = axes[0]
    keys, ctrls, viols, labels = [], [], [], []
    for key, metric in (("1 wrong dynamics", "pole_error"), ("2 wrong kernel", "residual_rmse"),
                        ("3 wrong noise", "accuracy"), ("4 wrong speaker geometry", "held_out_rmse"),
                        ("5 wrong acoustic map", "pole_error"), ("6 wrong dimensionality", "pole_error")):
        c, v = pair(key, metric)
        if c is None or v is None:
            continue
        keys.append(key)
        ctrls.append(abs(float(c)))
        viols.append(abs(float(v)))
        labels.append(metric)
    idx = np.arange(len(keys))
    ax.barh(idx - 0.19, ctrls, height=0.34, color=PALETTE[2], label="assumption satisfied")
    ax.barh(idx + 0.19, viols, height=0.34, color=PALETTE[1], label="assumption violated")
    ax.set_yticks(idx, [f"{k}\n({m})" for k, m in zip(keys, labels, strict=True)], fontsize=7)
    ax.invert_yaxis()
    ax.set_xscale("log")
    ax.set_xlabel("metric value (log scale; higher is worse except row 3, accuracy)")
    ax.set_title("Each assumption, broken once")
    ax.grid(axis="y", visible=False)
    ax.legend(fontsize=7.5, loc="lower right")

    ax = axes[1]
    U, U0 = invert_with(ok, ok.phi)  # ORACLE
    fit_ok = fit_trajectory_second_order(U, ok.config.grid.dt, U0)
    Unl, U0nl = invert_with(nl, nl.phi)  # ORACLE
    fit_nl = fit_trajectory_second_order(Unl, nl.config.grid.dt, U0nl)
    t_ms = ok.t * 1000.0
    r_ok = (U - _simulate_like(fit_ok, U, U0, ok.config.grid.dt))[0]
    r_nl = (Unl - _simulate_like(fit_nl, Unl, U0nl, nl.config.grid.dt))[0]
    ax.plot(t_ms, r_ok[:, 0], color=PALETTE[2], label="linear world (assumption holds)")
    ax.plot(t_ms, r_nl[:, 0], color=PALETTE[1], linestyle="--", label="cubic world (assumption broken)")
    ax.axhline(0, color=MUTED, linewidth=0.9)
    ax.set_xlabel("time within segment (ms)")
    ax.set_ylabel("fit residual, latent dim 1")
    ax.set_title("Residual structure is the only warning you get")
    ax.legend(fontsize=7.5)

    caption(
        fig,
        "Left: how far each broken assumption moves its own diagnostic. Right: the mis-specified "
        "dynamics fit produces a residual with visible time structure, whereas the correctly "
        "specified one does not — for several of these violations that is the only signal that "
        "anything is wrong.",
    )
    fig.tight_layout()
    save(fig, "assumption_stress_test", run)

    run.print_summary()
    run.save()


