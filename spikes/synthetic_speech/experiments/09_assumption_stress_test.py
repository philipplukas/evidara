def _simulate_like(fit, U, U0, dt):
    """Re-simulate a TrajectoryFit so its residual can be inspected."""
    from analysis.system_id import _zoh

    d = U.shape[-1]
    A = np.zeros((2 * d, 2 * d))
    A[:d, d:] = np.eye(d)
    A[d:, :d], A[d:, d:] = fit.A_u, fit.A_v
    B = np.zeros((2 * d, d))
    B[d:, :] = -fit.A_u
    Ad, Bd = _zoh(A, B, dt)
    x = np.concatenate([U0, np.tile(fit.v0, (U0.shape[0], 1))], axis=1)
    out = np.empty_like(U)
    out[:, 0] = x[:, :d]
    for k in range(U.shape[1] - 1):
        x = x @ Ad.T + fit.targets @ Bd.T
        out[:, k + 1] = x[:, :d]
    return out


def _best_linear_map(ds):
    """Least-squares linear approximation of the world's Phi over the visited latent range."""
    from acoustics import PolynomialAcousticMap

    u = ds.latent_u.reshape(-1, ds.config.d_art)[::37]  # GT: fitting a surrogate to the true map
    s = ds.phi.Phi(u)  # ORACLE: the surrogate is a deliberate mis-specification of a known map
    W, *_ = np.linalg.lstsq(u, s, rcond=None)
    return PolynomialAcousticMap(W=W.T, Q=np.zeros((s.shape[1], u.shape[1], u.shape[1])))


def _speaker_row(base, seed):
    """Compact re-run of the group/groupoid comparison, scored as held-out rmse."""
    out = {}
    for label, regime in (("control (group world)", "group"), ("violated (groupoid world)", "group")):
        world = speaker_world("groupoid" if "groupoid" in label else "group", 8, base)
        ds = generate(world, seed=seed)
        ref, per_speaker = {}, []
        for ti, (q, r) in enumerate(ds.transitions):
            ref[ti] = ds.observed[ds.mask(q, r, speaker=0)].mean(axis=0)
        for s in range(1, 8):
            X, Y = [], []
            for ti, (q, r) in enumerate(ds.transitions):
                sel = ds.mask(q, r, speaker=s)
                if sel.sum() >= 4:
                    half = sel.nonzero()[0]
                    X.append(ref[ti])
                    Y.append(ds.observed[half[: len(half) // 2]].mean(axis=0))
            if not X:
                continue
            Xc, Yc = np.concatenate(X), np.concatenate(Y)
            Xa = np.hstack([Xc, np.ones((Xc.shape[0], 1))])
            coef, *_ = np.linalg.lstsq(Xa, Yc, rcond=None)
            per_speaker.append(rmse(Yc, Xa @ coef))
        out[label] = dict(held_out_rmse=float(np.mean(per_speaker)), regime=regime)
    return out


if __name__ == "__main__":
    main()
