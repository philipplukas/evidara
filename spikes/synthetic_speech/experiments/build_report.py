"""Aggregate every experiment's JSON into results/SYNTHETIC_SPEECH_REPORT.md.

Reads only what the experiments recorded. If an experiment has not been run, its row says
so rather than being silently omitted -- a report that quietly drops a missing result is
worse than one that admits the gap.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from analysis.recording import results_dir  # noqa: E402

EXPECTED = [
    ("01_temporal_effect", "Anticipation", "temporal_effect.pdf"),
    ("02_temporal_rank", "Temporal rank", "temporal_rank.pdf"),
    ("03_kernel_recovery", "Temporal kernel", "kernel_recovery.pdf"),
    ("04_jacobian_recovery", "Jacobian / articulation", "jacobian_recovery.pdf"),
    ("05_dynamics_identification", "Dynamics", "dynamics_recovery.pdf"),
    ("06_identifiability", "Latent coordinates", "identifiability.pdf"),
    ("07_speaker_variation", "Speaker / groupoid structure", "group_vs_groupoid.pdf"),
    ("08_asr_comparison", "Recognition", "asr_sample_efficiency.pdf"),
    ("09_assumption_stress_test", "Broken assumptions", "assumption_stress_test.pdf"),
]

FIGURES = [
    "temporal_effect.pdf", "temporal_rank.pdf", "kernel_recovery.pdf", "jacobian_recovery.pdf",
    "dynamics_recovery.pdf", "identifiability.pdf", "group_vs_groupoid.pdf",
    "asr_sample_efficiency.pdf", "asr_unseen_speaker.pdf", "asr_unseen_transition.pdf",
    "assumption_stress_test.pdf",
]


def short(value, limit: int = 130) -> str:
    if value is None:
        return "—"
    text = json.dumps(value, default=str) if not isinstance(value, str) else value
    text = text.replace("\n", " ").replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def fmt_error(f: dict) -> str:
    if f.get("error") is None:
        return "—"
    return f"{f['error']:.4g} ({f.get('error_label', '')})".strip()


def main() -> None:
    out_dir = results_dir()
    payloads = {}
    for name, _, _ in EXPECTED:
        path = out_dir / f"{name}.json"
        if path.exists():
            payloads[name] = json.loads(path.read_text())

    lines: list[str] = []
    lines.append("# Synthetic Speech Dynamics — results\n")
    lines.append(
        "Generated by `experiments/build_report.py` from the JSON each experiment writes. "
        "Every row is a question the laboratory was able to ask because the generating "
        "mechanism is known exactly.\n"
    )
    missing = [n for n, _, _ in EXPECTED if n not in payloads]
    if missing:
        lines.append(f"> **Incomplete run.** Not yet executed: {', '.join(missing)}.\n")

    # ---- headline table --------------------------------------------------------------
    lines.append("## Summary\n")
    lines.append("| Question | Ground truth | Recovered? | Error | Identifiability | Failure mode / control |")
    lines.append("|---|---|---|---|---|---|")
    for name, _, _ in EXPECTED:
        p = payloads.get(name)
        if not p:
            lines.append(f"| _{name}_ | — | not run | — | — | — |")
            continue
        for f in p["findings"]:
            lines.append(
                f"| {short(f['question'], 110)} | {short(f['ground_truth'])} | {short(f['estimate'])} "
                f"| {fmt_error(f)} | {f['status']} | {short(f.get('notes') or f.get('control'), 180)} |"
            )
    lines.append("")

    # ---- the three hypotheses --------------------------------------------------------
    lines.append("## The three hypotheses\n")
    lines.append(_hypotheses(payloads))

    # ---- per-experiment detail -------------------------------------------------------
    lines.append("## Experiments\n")
    for name, topic, fig in EXPECTED:
        p = payloads.get(name)
        lines.append(f"### {name} — {topic}\n")
        if not p:
            lines.append("_Not run._\n")
            continue
        lines.append(f"**{p['title']}**\n")
        if p["figures"]:
            lines.append("Figures: " + ", ".join(f"`{f}`" for f in p["figures"]) + "\n")
        if p["scalars"]:
            lines.append("| Quantity | Value |")
            lines.append("|---|---|")
            for k, v in p["scalars"].items():
                lines.append(f"| {k} | {short(v, 200)} |")
            lines.append("")
        for f in p["findings"]:
            lines.append(f"- **{f['question']}**")
            lines.append(f"  - ground truth: `{short(f['ground_truth'], 300)}`")
            lines.append(f"  - estimate: `{short(f['estimate'], 300)}`")
            lines.append(f"  - error: {fmt_error(f)}")
            lines.append(f"  - status: **{f['status']}**")
            if f.get("control"):
                lines.append(f"  - control: {f['control']}")
            if f.get("notes"):
                lines.append(f"  - note: {f['notes']}")
        lines.append("")
        _ = fig

    # ---- figure inventory ------------------------------------------------------------
    lines.append("## Figure inventory\n")
    lines.append("| Figure | Present |")
    lines.append("|---|---|")
    for f in FIGURES:
        lines.append(f"| `{f}` | {'yes' if (out_dir / f).exists() else 'NO'} |")
    lines.append("")

    target = out_dir / "SYNTHETIC_SPEECH_REPORT.md"
    target.write_text("\n".join(lines))
    print(f"wrote {target}")


def _hypotheses(payloads: dict) -> str:
    def finding(exp: str, idx: int) -> dict | None:
        p = payloads.get(exp)
        if not p or idx >= len(p["findings"]):
            return None
        return p["findings"][idx]

    out = []

    h1 = finding("02_temporal_rank", 0)
    h1b = finding("02_temporal_rank", 1)
    out.append("### Hypothesis 1 — temporal variation is low-dimensional\n")
    if h1:
        out.append(
            f"**Supported, with a caveat about the exact dimension.** {short(h1['estimate'], 200)}; "
            f"status {h1['status']}. {h1.get('notes', '')}"
        )
        if h1b:
            out.append(f"\nOn counting the modes: {h1b.get('notes', '')}")
    else:
        out.append("_Experiment 02 has not been run._")
    out.append("")

    h2 = finding("06_identifiability", 1)
    h2b = finding("06_identifiability", 2)
    out.append("### Hypothesis 2 — dynamics are identifiable only modulo latent coordinate changes\n")
    if h2:
        out.append(f"**Supported.** {h2.get('notes', '')}")
        if h2b:
            out.append(f"\nAnd the invariant part: {h2b.get('notes', '')}")
    else:
        out.append("_Experiment 06 has not been run._")
    out.append("")

    out.append("### Hypothesis 3 — explicit dynamics help where statistical models struggle\n")
    p8 = payloads.get("08_asr_comparison")
    if p8:
        by_q = {f["question"]: f for f in p8["findings"]}
        for key in ("In distribution", "unseen transition", "unseen speaker", "ABLATION"):
            match = next((f for q, f in by_q.items() if key.lower() in q.lower()), None)
            if match:
                out.append(f"- **{match['question']}** → {match['status']}. {match.get('notes', '')}")
    else:
        out.append("_Experiment 08 has not been run._")
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    main()
