/**
 * Pixel baselines for the admin run-detail v2 layout.
 *
 * WHY THIS FILE IS HERE AND NOT IN `legal-search/frontend/e2e/` (#913)
 * --------------------------------------------------------------------
 * This capture used to live in `legal-search/frontend/e2e/visual.spec.ts`, with its
 * baseline PNG committed under that surface's `visual.spec.ts-snapshots/`. Two costs,
 * both measured:
 *
 * 1. A PNG has no merge strategy. Any two branches that touch admin layout collide on
 *    one binary file and cannot be merged — PRs #902 and #905 hit exactly that.
 * 2. An admin change broke a *legal-search* CI job, which is undiscoverable from the
 *    admin tree (#895). The failing job named a surface the author had not touched.
 *
 * The capture is unchanged in intent: the "Run overview" decision quadrant (the
 * `Why this matters` primary card plus its three subordinate cards) and the collapsed
 * lifecycle accordion stack below it. `RunShowV2` renders no layout that any Vitest
 * layer can see — jsdom has no layout engine and applies no stylesheet — so this is
 * the only guard on that quadrant's geometry.
 *
 * ZERO PIXEL TOLERANCE. `playwright.config.ts` sets no `maxDiffPixelRatio`, which
 * means Playwright's default: zero differing pixels. Do not add a project-level
 * tolerance. On a 1600x900 full-page shot a 6% ratio is ~86k pixels of licensed
 * drift, which is how the legal-search suite stayed green across a ~260px mislaid
 * filter rail for 3.5 months (#605/#611). If one snapshot genuinely needs slack,
 * scope it to that one `toHaveScreenshot` call with a written justification.
 *
 * Baselines are generated by the `admin-visual-baseline-refresh` CI job (add the
 * `visual-baseline-refresh` label to the PR, then push) so generation and
 * verification share an environment — see `visual.spec.ts-snapshots/PROVENANCE.md`.
 *
 * Every request is mocked with `page.route`, as every spec in this directory does.
 * No backend, no database.
 *
 * Selection: tagged `@visual` so `npm run e2e` (which runs `--grep-invert @visual`)
 * leaves it to the dedicated `npm run e2e:visual` job. Both are invoked by
 * `.github/workflows/platform-control.yml`, which is what
 * `scripts/check-e2e-spec-coverage.sh` asserts.
 */

