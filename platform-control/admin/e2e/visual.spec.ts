const EMPTY_PAGE = { data: [], total: 0, limit: 100, offset: 0 };

async function mockRunDetail(page: Page) {
  // Benign catch-all first (lowest priority), so any read model not named below
  // resolves to an empty 200 rather than hanging — an in-flight request leaves a
  // spinner in the frame, and a spinner in a pixel baseline is nondeterminism.
  await page.route("**/api/platform-control/**", (route) =>
    route.fulfill({
      status: 200,
      contentType: "application/json",
      body: JSON.stringify(EMPTY_PAGE),
    }),
  );

  const json = (body: unknown) => (route: Route) =>
    route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(body) });

  await page.route(`**/v1/runs/${RUN_ID}/pipeline-health`, json(PIPELINE_HEALTH));
  await page.route(`**/v1/runs/${RUN_ID}`, json(RUN));
}

test.describe("Visual regressions @visual", () => {
  test("run detail v2 — primary decision hierarchy matches baseline", async ({ page }) => {
    // Next `dev` compiles routes lazily on first request, and admin's shared
    // `@evidara/ui` tree makes that first cold compile expensive (PR #503). Give the
    // first navigation headroom so a one-time compile is not read as a layout bug.
    test.setTimeout(120_000);

    await page.addInitScript(() => {
      window.localStorage.setItem("evidara_user_role", "admin");
    });
    await mockRunDetail(page);
    await page.setViewportSize({ width: 1600, height: 900 });

    await page.goto(`/#/runs/${RUN_ID}/show`, { waitUntil: "load", timeout: 90_000 });

    // `exact: true` matters here. Playwright's `name` is a SUBSTRING match by
    // default, and `PipelineHealthBanner` renders a second heading further down the
    // page — "Pipeline decision support". A non-exact locator resolves to both, and
    // the `toHaveCount(1)` below then asserts nothing about the quadrant it names.
    const decisionSupport = page.getByRole("heading", { name: "Decision support", exact: true });
    await expect(decisionSupport).toBeVisible({ timeout: 20_000 });
    await expect(page.getByRole("heading", { name: new RegExp(`Run ${RUN_ID}`) })).toBeVisible({
      timeout: 20_000,
    });
    // `RunDetailSectionsV2` renders collapsed accordion items below the metadata
    // grid. Waiting for the last of them means the capture includes the full
    // lifecycle stack rather than racing a half-rendered page.
    await expect(page.getByRole("button", { name: /Provider Jobs/ })).toBeVisible({
      timeout: 20_000,
    });

    // Anti-duplicate assertion. Pixel tolerance is zero here, but a *structural*
    // regression like a double-mounted quadrant can still produce a stable image;
    // this DOM-level check cannot be satisfied by one.
    await expect(decisionSupport).toHaveCount(1);

    await expect(page).toHaveScreenshot("run-detail-v2.png", { fullPage: true });
  });
});
